// 猫背の見分け方（tools/coach.py と同じ。2026-11-02 のトレッドミルで確かめた）
//   まっすぐ立ったとき（カメラの直立の基準を取った3秒）の胸のセンサーの重力の向きを覚え、そこからの傾きを見る。
//   走り出して skip 秒たってから learn 秒の傾きの真ん中の値を「走る前傾」にする（走る前傾は人と速さで変わるので、線はそこから決める）。
//   そのあと走っている間、傾きが「走る前傾 + margin」を hold 秒続けて超えたら胸を震わせ、超えたままなら cooldown 秒ごとに繰り返す。
//   実機：ふつうに走って胸 約12〜16°、猫背 約26〜28°、胸を張って 約18°。立った姿勢からの決まった 18° では、ふつうの走りでも鳴った
export const HUNCH = {
  ema: 0.02, // 加速度をならす割合（1件ごと。100Hz で約0.5秒）。ならした向きを重力の向きとみなす
  standMin: 100, // 立った姿勢を覚えるのに要る件数（100Hz で1秒）
  skip: 10, // 走り出してから、走る前傾を覚え始めるまで（秒。走った時間だけ数える）
  learn: 30, // 走る前傾を覚える長さ（秒）
  learnMin: 50, // その間に取れた傾きがこれより少なければ、覚えずに取り直す（10回/秒で5秒）
  margin: 8, // 走る前傾からこれ以上（度）傾いたら猫背
  hold: 1.5, // それが続いたら知らせる（秒）
  cooldown: 4, // 超えたままなら、この間隔（秒）で知らせ直す。本人が試して、ちょうどよかった
  buzzCount: 1, // 振動の回数と長さ（ミリ秒）。0.2秒では走りながら気づきにくかった。長さは最大 2.55秒
  buzzMs: 1000,
  tick: 0.1, // 判定する間隔（秒）
  stale: 1, // 胸の値がこれ（秒）より古ければ、傾きは無いものとする（切れている間に、止まった値で覚えたり知らせたりしない）
}

