//   前の向きは、走る前傾が fwdMin 度より大きいときだけ決める。小さいと向きが揺れで決まって本当の前とずれ、前に出た頭を数えなかった（2026-11-05：頭 2.9°・胸 6.1°）。
//     fwdMin 1 → 8 で、記録5本を流し直すと、11-05 の頭の知らせ 0 → 11回（カメラの「頭が前」9回のうち5回に±15秒で合う）。ほかの走りの回数は変わらない
//   ずれの見張り：線を越えていた時間が slipSec 秒に達するか、寄せた基準が走る前傾から slipDrift 度より前へ動いたら、
//   崩れではなくセンサーの付け位置がずれたとみなし、基準を今の傾きへ置き直して、短く slipBuzzCount 回震わせる（走ったあとの結果の画面で「付け直して」と知らせる）
//   slipSec 75・slipDecay 1：わざとの猫背 60秒（60秒あけて2回でも）は置き直さず、急にずれて越えたままなら約75秒で黙る（sim/result-lean-slip.md）。
//   その代わり、75秒より長く崩れたままだと、ずれとみなして黙る
export interface LeanParams {
  place: string // 見る場所（SLOTS の place）。知らせるときも、ここを震わせる
  ema: number // 加速度をならす割合（1件ごと。100Hz で約0.5秒）。ならした向きを重力の向きとみなす
  standMin: number // 立った姿勢を覚えるのに要る件数（100Hz で1秒）
  skip: number // 走り出してから、走る前傾を覚え始めるまで（秒。走った時間だけ数える）
  learn: number // 走る前傾を覚える長さ（秒）
  learnMin: number // その間に取れた傾きがこれより少なければ、覚えずに取り直す（10回/秒で5秒）
  fwdMin: number // 走る前傾を覚える間に、立った姿勢からこれ（度）以上傾いていなければ、前の向きを決めず、向きによらない角度を使う（下の LEAN の説明）
  margin: number // 基準からこれ以上（度）前に傾いたら崩れ
  follow: number // 基準を今の傾きへ寄せる時定数（秒）。0 なら寄せない
  hold: number // それが続いたら知らせる（秒）
  cooldown: number // 超えたままなら、この間隔（秒）で知らせ直す。本人が試して、ちょうどよかった
  buzzCount: number // 振動の回数と長さ（ミリ秒）。0.2秒では走りながら気づきにくかった。長さは最大 2.55秒
  buzzMs: number
  tick: number // 判定する間隔（秒）
  stale: number // 値がこれ（秒）より古ければ、傾きは無いものとする（切れている間に、止まった値で覚えたり知らせたりしない）
  slipSec: number // 線を越えていた時間がこれ（秒）に達したら、センサーがずれたとみなして基準を置き直す。0 なら見張らない
  slipDecay: number // 線の下にいる間、越えていた時間をこの倍の速さで減らす（1 なら、越えていたのと同じ長さだけ線の下にいれば 0 に戻る。0.5 では、わざと 60秒 ×2（間60秒）を20通りのうち18回ずれとみなした）
  slipDrift: number // 寄せた基準が、走る前傾（前にずれとみなしたときは、そのときの基準）からこれ（度）より前へ動いたら、ずれとみなす。0 なら見ない
  slipRef: number // 置き直す先：直近これ（秒）の傾きの真ん中の値
  slipBuzzCount: number // ずれたと知らせる振動（崩れの1秒1回と分けて、0.3秒を3回）。走りながら気づけるかは、まだ試していない
  slipBuzzMs: number
  // 体を曲げた（物を拾う・靴ひもを結ぶ）：傾きが基準 + bend（度）以上なら、走る姿勢ではないとみなし、知らせない。0 なら見ない。
  //   曲げている間と、戻ってから bendAfter 秒は、知らせず、基準も寄せず、ずれの見張りにも数えない（越え始めてからの分もなかったことにする）。
  //   胸で曲げたと見たら、頭もいっしょに止める（session.ts。頭は曲げるより先に下を向くので、頭だけでは見分けられない）
  bend: number
  bendAfter: number
  // 線を越えて最初に知らせるときの傾きが基準 + confirmAbove（度）以上なら、confirmSec 秒待って、その間に曲げたと分からなければ知らせる（0 なら待たない）。
  //   曲げる途中の傾きで先に震わせないため（2026-11-04 の3回は、頭の知らせが胸で曲げたと分かる約0.4秒前だった）
  confirmAbove: number
  confirmSec: number
  // カメラ版のずれの見張り：線を越えて camSlipSec 秒たっても、カメラの上体の前傾の真ん中が camRise 度、頭の位置（肩→耳）の真ん中が camHeadRise 度も、
  // 線の下にいた直近 camRef 秒の真ん中より増えていなければ、ずれとみなす。両方にカメラの値が camMin 件（tick の数）なければ見ない。camSlipSec が 0 なら見ない
  camSlipSec: number
  camRise: number
  camHeadRise: number
  camRef: number
  camMin: number
  // 2つの立ち方（いつもの楽な立ち方 a と、胸を開いた立ち方 b）で見る（lean.ts の setPoses。下の POSE の説明）。すべて仮の値（確かめ走で決める）
  poseMin: number // a と b の向きの差（度）がこれより小さければ、姿勢を変えられていないとみて測り直す（使い切ったら今までの見方）
  poseLine: number // 線の幅（度、決まった値）。b から b→a の向きに沿って「差し引いた走る前傾 + poseLine」を越えたら崩れ。0 なら下の poseFrac で決める（頭）
  poseFrac: number // poseLine が 0 のとき：猫背の割合（b ＝ 0、a ＝ 1）がこれを越えたら崩れ。線は b からの「走りの前傾の分 + poseFrac × a と b の差」。ただし margin（poseMargin）より狭くはしない
  poseCap: number // 走り出しの前傾として差し引くのは、b からこれ（度）まで（猫背のまま走り出しても、猫背を基準にしないため。頭。胸は poseSpeed）
  poseSpeed: boolean // 胸：差し引く分を、走り出しの前傾ではなく、その速さのよい例の前傾から決める（下の CHEST_EXPECT。poseCap は使わない）
  // ずれと猫背の見分け（2つの立ち方で見るときだけ）：線を越えている向きが猫背としてありうる間は、ずれの見張り（slipSec）に数えない。
  //   ありうる：b→a の向きに沿った傾き（差し引いた走る前傾を除く）が min(poseIdxMin × 差, 線の幅)〜poseSlipIdx × 差 で、b→a と直角な横の傾きが max(poseSlipSide, poseSlipSideFrac × 差) 以下。
  //   下の端を線の幅までにするのは、線を決まった度数（poseLine）にしたので、差が大きい人（差 25° で 0.4 × 25 = 10°）は、線（5°）を越えても割合が poseIdxMin に届かず、
  //   猫背なのにずれの見張りに数えてしまうため
  poseIdxMin: number
  poseSlipIdx: number
  poseSlipSide: number
  poseSlipSideFrac: number
  // 猫背のまま走り続けたとき、4秒ごとに震え続けないよう：続けて poseBackoffAfter 回知らせたら、poseBackoffEvery 秒ごとにする。
  // 線の下に poseBackoffReset 秒いたら数え直す
  poseBackoffAfter: number
  poseBackoffEvery: number
  poseBackoffReset: number
  // 2つの立ち方で見るときだけの、場所ごとの決まり（0 なら今までと同じ。頭で使う。下の HEAD の説明）
  poseMargin: number // 線の幅の下限（度）。0 なら margin
  poseHold: number // 線を越えてこれ（秒）続いたら知らせる。0 なら hold
  poseStart: number // 走り出してこれ（秒）から、走る前傾を覚え終わる前でも、poseCap を基準にして知らせる。0 なら覚え終わってから
  posePraise: number // 知らせたあと、線の下にこれ（秒）続けていたら、ほめる（短く praiseBuzzCount 回）。0 ならほめない
  praiseBuzzCount: number
  praiseBuzzMs: number
}

