// 前への傾きで崩れを見る（lean.ts の LeanDetector。胸＝猫背、頭＝頭が前に出る。2026-11-02 のトレッドミルで確かめた）
//   まっすぐ立ったとき（カメラの直立の基準を取った3秒）のセンサーの重力の向きを覚え、そこからの前への傾きを見る。
//   走り出して skip 秒たってから learn 秒の傾きの真ん中の値を「走る前傾」にする（走る前傾は人と速さで変わるので、線はそこから決める）。
//   線は「基準 + margin」。基準は走る前傾から始め、線の下にいる間だけ follow 秒の時定数でゆっくり今の傾きへ寄せる（ベルトのずれを吸う）。
//   傾きが線を hold 秒続けて超えたら、その場所を buzzMs 震わせ、超えたままなら cooldown 秒ごとに繰り返す。線の下に戻れば止まる
export interface LeanParams {
  place: string // 見る場所（SLOTS の place）。知らせるときも、ここを震わせる
  ema: number // 加速度をならす割合（1件ごと。100Hz で約0.5秒）。ならした向きを重力の向きとみなす
  standMin: number // 立った姿勢を覚えるのに要る件数（100Hz で1秒）
  skip: number // 走り出してから、走る前傾を覚え始めるまで（秒。走った時間だけ数える）
  learn: number // 走る前傾を覚える長さ（秒）
  learnMin: number // その間に取れた傾きがこれより少なければ、覚えずに取り直す（10回/秒で5秒）
  fwdMin: number // 走る前傾を覚える間に、立った姿勢からこれ（度）以上傾いていなければ、前の向きを決めず、向きによらない角度を使う
  margin: number // 基準からこれ以上（度）前に傾いたら崩れ
  follow: number // 基準を今の傾きへ寄せる時定数（秒）。0 なら寄せない
  hold: number // それが続いたら知らせる（秒）
  cooldown: number // 超えたままなら、この間隔（秒）で知らせ直す。本人が試して、ちょうどよかった
  buzzCount: number // 振動の回数と長さ（ミリ秒）。0.2秒では走りながら気づきにくかった。長さは最大 2.55秒
  buzzMs: number
  tick: number // 判定する間隔（秒）
  stale: number // 値がこれ（秒）より古ければ、傾きは無いものとする（切れている間に、止まった値で覚えたり知らせたりしない）
}

const LEAN = {
  ema: 0.02,
  standMin: 100,
  skip: 10,
  learn: 30,
  learnMin: 50,
  fwdMin: 1,
  follow: 60,
  hold: 1.5,
  cooldown: 4,
  buzzCount: 1,
  buzzMs: 1000,
  tick: 0.1,
  stale: 1,
}

// 胸の猫背。実機：ふつうに走って胸 約12〜16°、猫背 約26〜28°、胸を張って 約18°（立った姿勢から）。立った姿勢からの決まった 18° では、ふつうの走りでも鳴った。
// follow：2026-11-02 20:23 の走り（カメラの上体は 2〜8° でまっすぐ）で、胸の傾きがベルトのずれで3分半に約15°増え、寄せないと2分すぎから鳴り続けた（16回）。
// 60秒で寄せると3回（そのうち2回は、カメラの上体も +4〜5° 動いた数秒）。わざとの猫背（Mac のテスト、40秒・+14°）は寄せても同じく9回鳴る。
// その代わり、ゆっくり進む崩れは吸ってしまう：+12° なら約50秒、+15° なら約75秒、+20° なら約2分より時間をかけて進むと鳴らない
export const HUNCH: LeanParams = { ...LEAN, place: CHEST, margin: 8 }

