// 項目ごとの線（度。腰は %）。この値以下なら満点、zero 以上で0点、その間は比例。cue を越えたら声をかける
//   head：走り始め（HIP_REF の区間）の自分から、頭が前に出た量。立って測った基準とは比べない
//   （研究データ Riglet 2024、23人：走ると上体だけ前に傾くので、首の角度は立ったときより平均 8.8° 小さく、
//    人により −24〜+13° と違う。立った基準と比べると、頭を前に出しても2割しか気づけなかった。走り始めと比べると9割）
//   頭が前に出た量は、首の角度（肩→耳の前傾 − 腰→肩の前傾）の増えと、頭の位置そのもの（肩→耳の前傾）の増えの、小さいほう。
//   首の角度だけで見ると、上体が起きた分だけ首の角度が増え、頭は動いていないのに「頭が前」になる
//   （人の動画で、腰落ちの例が上体 −9.4°・頭の位置 +1.4° で「頭が前」と言ってしまった。form-videos/notes/判定テスト.md）。
//   頭の位置そのものだけで見ると、体ごと前に倒したときにも頭が前に出て測れる（トレッドミルの記録の「体ごと前に」で +27°）
//   head の線は、仮想実験（sim/result-coach.md、Riglet の59本、実機なみのずれ、上級）で、5° ではふつうに走るだけで
//   10分あたり約5回の誤った声が出た。8° で 1.3 回に減り、6° 前に出したときに見つける割合は変わらなかった
//   trunk：腰の中心→肩の中心の線の前傾。body：足首の中心→肩の中心の線の前傾（1秒の平均）
//   body の線は、研究データ（Van Hooren 2024、16人）で、ふつうに走ると 7〜13°（平均10.4°）、
//   わざと前に倒すと平均14.4° だったので、14° を越えたら声をかける
//   trunkBack・bodyBack：上体・体全体の起きすぎ（後ろへの傾き）。値は鉛直から後ろへの傾き（前傾が −5° なら 5）。
//   基準ができる前は、はっきり後ろに傾いたときだけ声をかける（上体が 5° より後ろ、体全体が 1° より後ろ）。
//   人の動画では、作者が「起きすぎ」と言う例でも上体 0〜1.6°、体全体 2〜5° と前に傾いていた
//   hip：走り始め（30秒〜3分）の自分の腰の高さからの下がり（脚の長さに対する%）。仮想実験で、4% ならふつうに走って
//   誤った声はほとんど出ず（Riglet の59本で0、RBDS の54本で10分あたり 0.06 回）、4% 落とした腰を見つけた（6% では、4% 落としても気づけなかった）。
//   トレッドミルの記録（2026-10-19）では、ふつうの区間の6秒平均の下がりは最大 2.8% で、4% との差は小さい
