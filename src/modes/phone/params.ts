// しくみの数字（CUE・QUIET・SCORE など）は src/core/params.ts のものをそのまま使い、ここでは決めない

// センサーの値の読み方
export const PHONE = {
  fs: 50, // 測った値を、この間隔（毎秒の回数）に並べ直してから計算する。iPhone の DeviceMotion は毎秒約60回
  window: 4, // 直近この長さ（秒）の値から、ピッチ・上下動・ブレーキ・前傾を出す
  minWindow: 2.5, // 値がこれ（秒）より短いうちは出さない
  gapReset: 0.5, // 値の間があいたら（秒）、つながらないので捨てて測り直す
  spmMin: 120, // ピッチを探す範囲（歩／分）。1歩の周期 0.25〜0.5 秒。2歩（1周期）の山を1歩と取り違えない範囲
  spmMax: 240,
  refineSpan: 0.06, // 自己相関で出した1歩の周期を、この割合（±）の範囲で細かく探し直す
  refineSteps: 12, // その片側の刻みの数
  harmonics: 10, // 前後の向きを決めるとき、1歩の周期の何倍の細かさの波まで見るか（毎秒25回の上限で打ち切る）
  minRegularity: 0.5, // 上下の加速度の、1歩ずらした自己相関がこれ以上なら、1歩ごとにそろった動き（走っている）とみなす
  runAccRms: 3, // 上下の加速度のばらつき（m/s²）がこれ以上なら、走る強さの動き。歩きと分ける（仮。実機で確かめる）
  stillStd: 0.3, // 立って止まっているとみなす、加速度のばらつき（m/s²）の上限。前傾の基準を取るとき
  gravityMin: 7, // 平均の加速度の大きさ（m/s²）がこの範囲にないときは、向きが落ち着いていないので出さない
  gravityMax: 12.5,
}

// 項目ごとの線。どれも走り始め（HIP_REF の区間）の自分からの崩れ。大きいほど崩れている向きにそろえている
// どれも仮の線。トレッドミルで、カメラ版を答えにして確かめるまでは、この値を信じすぎない
//   cadence：走り始めからのピッチの下がり（%）。Heiderscheit ら 2011（Med Sci Sports Exerc 43:296-302）で、
//     ピッチを 5% 上げるだけで膝・股関節の負担がはっきり減ったため、5% 下がったら声をかける
//   bounce：走り始めからの上下動の増え（cm）。根拠となる研究データはまだない（仮）
//   braking：走り始めからの、1歩ごとの前後の速さの落ち込みの増え（m/s）。根拠となる研究データはまだない（仮）
//   lean：走り始めからの上体の前傾の増え（度）。カメラ版の体幹と同じ線（src/core/params.ts の REL_LIMITS.trunk）を使う
export const PHONE_LIMITS: Record<'cadence' | 'bounce' | 'braking', { full: number; zero: number; cue: number }> = {
  cadence: { full: 3, zero: 10, cue: 5 },
  bounce: { full: 1, zero: 3, cue: 2 },
  braking: { full: 0.05, zero: 0.15, cue: 0.1 },
}
