  tau: 3, // ならしの時定数（秒）。長いほどゆれは減るが、減速に気づくのが遅れる。根拠なし（仮）
  band: 0.1, // 走り始めの基準の速さから ±この割合を外れた秒は判定しない。根拠なし（仮。実機で決める）
