// 速さで判定を止める（docs/phone-spec.md 機能4、speed.ts）。外で走るとき、ペースを落とした・上り坂でゆっくりになった・
// インターバルで速くした、などでピッチ・上下動・ブレーキが自然に変わるのを「崩れ」と言わないため
// （ピッチ・上下動・ブレーキは、どれも走る速さで変わる：van Oeveren 2019、Baker 2025、Wang 2020）。
// トレッドミル（実機テスト）では速さが一定なので使わない（「トレッドミルで試す」）
//   GPS の速さは、そのままだとゆれが大きい。低い周波数だけ通すフィルタで、インターバル走での速さの誤差を最大 80% 減らせた
//   （Biernacki 2023）。ここでは1次のフィルタ（時定数 tau）にした。フィルタの形と時定数そのものには研究の根拠はない
//   band（何%外れたら止めるか）は研究の根拠のない仮の値で、外で走った記録（1秒ごとの speed・gate の列）で決め直す。
//     速さとピッチの関係は人によって違い（van Oeveren 2019）、何%速さが変わるとピッチが5%（声の線）動くかの数字は確かめていない。
//     考え方：ふつうのジョグのペースのゆれやフィルタ後の GPS のゆれ（数%）では止まらず、信号の手前の減速・上り坂・
//     インターバルのような、はっきりしたペースの変化（6:00/km なら ±35秒/km ほど）で止まる幅にした。迷ったら声をかけない側に倒す
// 坂（気圧計の案）：ウェブでは気圧計が使えない。GPS の高さは横の位置より誤差が大きく（ブラウザが出す altitudeAccuracy は
//   ふつう数m〜十数m。研究で確かめた数字ではない）、5% の坂でも 100m 走って 5m しか上がらないので、
//   数秒〜数十秒の高さの変化から坂を見分けられない。だから坂は見ない（上り坂でペースが落ちれば、速さで止まる）。
//   GPS の高さは、あとで確かめられるよう記録にだけ残す。坂は iPhone アプリにして気圧計（CMAltimeter）で見る
