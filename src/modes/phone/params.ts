// 項目ごとの線。どれも走り始め（PHONE_REF の基準）の自分からの崩れ。大きいほど崩れている向きにそろえている
// どれも仮の線。トレッドミルで、カメラ版を答えにして確かめるまでは、この値を信じすぎない
//   cadence：走り始めからのピッチの下がり（%）。Heiderscheit ら 2011（Med Sci Sports Exerc 43:296-302）で、
//     ピッチを 5% 上げるだけで膝・股関節の負担がはっきり減ったため、5% 下がったら声をかける
//   bounce：走り始めからの上下動の増え（cm）。根拠となる研究データはまだない（仮）
//   braking：走り始めからの、1歩ごとの前後の速さの落ち込みの増え（m/s）。根拠となる研究データはまだない（仮）
export const PHONE_LIMITS: Record<'cadence' | 'bounce' | 'braking', { full: number; zero: number; cue: number }> = {
  cadence: { full: 3, zero: 10, cue: 5 },
  bounce: { full: 1, zero: 3, cue: 2 },
  braking: { full: 0.05, zero: 0.15, cue: 0.1 },
}

