// 音で知らせる項目（ItemSpec.tone。いまはスマホのピッチだけ）。言葉は初めだけで、あとは音（メトロノーム）。
// 外れたときだけ鳴らし、戻ったら止め、くり返すほど間をあける（docs/research/phone-methods.md 4章）
//   言葉をくり返さず、外れたときだけ音で知らせる：Van den Berghe 2022（外れたときだけ音楽に雑音をかぶせた）
//   だんだん減らす：Winstein & Schmidt 1990（知らせの割合を減らすと身につく。走りの研究ではない）、
//     Crowell 2011・Bowser 2018（練習の後半で知らせを減らし、効果が続いた。どちらも何回かの練習をまたいで減らしている）
//   下の数字そのもの（何回まで言葉、何小節、何回目から・どれだけ間をあけるか）には、研究の根拠はない。実機で決め直す
export const TONE = {
  words: 1, // 言葉で言うのは、1回の走りでこの回数まで（初めの1回だけ）。あとは音だけ
  // 1回に鳴らすのは、この小節まで（1小節＝4拍、1拍＝1歩）。戻ればその前に止める。根拠なし。
  // 8小節は 170歩/分で約11秒：ピッチは直近4秒から出すので、テンポに合わせてから「戻った」と分かる（CUE.recoverHold）までに
  // およそ7〜9秒かかる（合わせるまでの数歩＋窓が入れ替わる時間＋3秒）。それより少し長く鳴らせば、合わせた人には「戻ったら止まる」が伝わり、合わせない人にも鳴りっぱなしにならない
  bars: 8,
  fadeFrom: 3, // この回数目の知らせまでは、ふつうの間（CUE.cooldown）で知らせる。根拠なし（音の意味を覚えるまでの2回は減らさない）
  fadeStep: 30, // そのあとは1回ごとに、次の知らせまでの間をこれだけのばす（秒）。根拠なし
  fadeMax: 180, // 一番長くて（秒）。根拠なし（声なしの見守りに入る長さ QUIET.enterWindow に合わせた）
}

